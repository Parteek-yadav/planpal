import { z } from "zod";

/**
 * Creative theme idea with palette swatches.
 */
export const ThemeIdeaSchema = z.object({
  title: z.string().min(1).max(80),
  description: z.string().min(1).max(300),
  colorPalette: z
    .array(z.string().regex(/^#[0-9A-Fa-f]{6}$/, "Must be valid 6-character hex color"))
    .min(3)
    .max(6),
});
export type ThemeIdea = z.infer<typeof ThemeIdeaSchema>;

/**
 * Event activity idea with target demographic and timing.
 */
export const ActivityIdeaSchema = z.object({
  name: z.string().min(1).max(80),
  description: z.string().min(1).max(300),
  targetAudience: z.string().min(1).max(80),
  durationMinutes: z.number().int().positive(),
});
export type ActivityIdea = z.infer<typeof ActivityIdeaSchema>;

/**
 * Food or drink menu suggestion tailored to dietary constraints.
 */
export const MenuSuggestionSchema = z.object({
  course: z.string().min(1).max(60),
  dishName: z.string().min(1).max(100),
  description: z.string().min(1).max(250),
  dietaryTags: z.array(z.string().min(1).max(40)).default([]),
});
export type MenuSuggestion = z.infer<typeof MenuSuggestionSchema>;

/**
 * Event decoration concept with materials and DIY budget tip.
 */
export const DecorationConceptSchema = z.object({
  focalArea: z.string().min(1).max(80),
  materials: z.string().min(1).max(200),
  diyBudgetFriendlyTip: z.string().min(1).max(250),
});
export type DecorationConcept = z.infer<typeof DecorationConceptSchema>;

/**
 * Consolidated personalized event ideas package generated by AI.
 */
export const PersonalizedIdeasSchema = z.object({
  eventSummary: z.string().min(1).max(400),
  themes: z.array(ThemeIdeaSchema).min(2).max(4),
  activities: z.array(ActivityIdeaSchema).min(2).max(5),
  menus: z.array(MenuSuggestionSchema).min(2).max(6),
  decorations: z.array(DecorationConceptSchema).min(2).max(5),
});
export type PersonalizedIdeas = z.infer<typeof PersonalizedIdeasSchema>;
